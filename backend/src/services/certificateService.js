const QRCode = require('qrcode');
const PDFDocument = require('pdfkit');

function buildVerificationCertificatePayload({
  document,
  verification,
  blockchain,
  status,
}) {
  return {
    certificateVersion: '1.0',
    generatedAt: new Date().toISOString(),
    document: {
      id: String(document?._id || document?.documentId || ''),
      title: document?.title || '',
      ownerName: document?.ownerName || '',
      issuingOrganization: document?.issuingOrganization || document?.issuer || '',
      documentType: document?.documentType || '',
      originalFileName: document?.originalFileName || null,
      uploadDate: document?.uploadDate || null,
      sha256Hash: document?.sha256Hash || verification?.hash || null,
      digitalSignature: document?.digitalSignature || null,
    },
    verification: {
      status,
      isAuthentic: Boolean(verification?.isAuthentic),
      verificationTimestamp: verification?.verificationTimestamp || null,
      hashMatches: verification?.tamperDetectionResult?.hashMatches ?? null,
      tamperDetectionDetails: verification?.tamperDetectionResult?.details || null,
    },
    blockchain: {
      transactionId: blockchain?.transactionId || null,
      confirmed: Boolean(blockchain?.confirmed),
      blockNumber: blockchain?.blockNumber ?? null,
      timestamp: blockchain?.timestamp ?? null,
      blockchainHash: verification?.blockchainHash || null,
    },
  };
}

async function generateQrCodeDataUrl(text) {
  return QRCode.toDataURL(text, { errorCorrectionLevel: 'M', margin: 1, width: 320 });
}

function generateCertificatePdf({ payload, qrDataUrl }) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 40 });
    const chunks = [];

    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header
    doc.fillColor('#0f172a');
    doc.fontSize(24).font('Helvetica-Bold').text('ChainVerify', { align: 'center' });
    doc.fontSize(10).fillColor('#64748b').text('Verification Certificate', { align: 'center' });
    doc.moveDown(0.5);

    // Document Info
    doc.fontSize(12).font('Helvetica-Bold').fillColor('#0f172a').text(payload.document.title);
    doc.fontSize(9).fillColor('#475569');
    doc.text(`Owner: ${payload.document.ownerName}`);
    doc.text(`Organization: ${payload.document.issuingOrganization}`);
    doc.text(`Type: ${payload.document.documentType}`);
    doc.moveDown(0.3);

    // Verification Status
    const statusColor = payload.verification.isAuthentic ? '#047857' : '#e11d48';
    doc.fontSize(11).font('Helvetica-Bold').fillColor(statusColor).text(`Status: ${payload.verification.status}`);
    doc.fontSize(9).fillColor('#475569');
    doc.text(`Authentic: ${payload.verification.isAuthentic ? 'Yes' : 'No'}`);
    doc.moveDown(0.3);

    // Hashes
    doc.fontSize(10).font('Helvetica-Bold').fillColor('#0f172a').text('Hash Verification');
    doc.fontSize(8).fillColor('#64748b').font('Helvetica');
    doc.text(`Database Hash: ${payload.document.sha256Hash || 'N/A'}`);
    doc.text(`Blockchain Hash: ${payload.blockchain.blockchainHash || 'N/A'}`);
    doc.moveDown(0.3);

    // Blockchain
    doc.fontSize(10).font('Helvetica-Bold').fillColor('#0f172a').text('Blockchain Record');
    doc.fontSize(9).fillColor('#475569').font('Helvetica');
    doc.text(`Transaction: ${payload.blockchain.transactionId || 'N/A'}`);
    doc.text(`Confirmed: ${payload.blockchain.confirmed ? 'Yes' : 'No'}`);
    doc.text(`Block: ${payload.blockchain.blockNumber ?? 'N/A'}`);
    doc.moveDown(0.3);

    // QR Code
    if (qrDataUrl) {
      try {
        doc.fontSize(10).font('Helvetica-Bold').fillColor('#0f172a').text('Verification QR');
        const buf = Buffer.from(qrDataUrl.split(',')[1], 'base64');
        doc.image(buf, { width: 150, align: 'center' });
      } catch (err) {
        doc.text('[QR Code unavailable]', { align: 'center' });
      }
    }

    doc.moveDown(0.5);
    doc.fontSize(8).fillColor('#94a3b8').text(
      'Generated by ChainVerify • Backed by blockchain records',
      { align: 'center' }
    );

    doc.end();
  });
}

module.exports = {
  buildVerificationCertificatePayload,
  generateQrCodeDataUrl,
  generateCertificatePdf,
};

