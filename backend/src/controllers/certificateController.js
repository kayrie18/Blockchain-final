function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '<')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

async function generateCertificate(req, res, next) {
  try {
    const documentId = String(req.params.documentId || '').trim();
    const format = String(req.query?.format || 'html').trim().toLowerCase(); // 'html' or 'pdf'

    if (!/^[a-f0-9]{24}$/i.test(documentId)) return res.status(400).json({ error: { message: 'A valid documentId is required' } });

    const doc = await Document.findById(documentId)
      .select('title ownerName issuingOrganization documentType uploadDate originalFileName sha256Hash digitalSignature blockchain status isRevoked expiryDate rejectionReason uploadedBy')
      .lean()
      .exec();

    if (!doc) return res.status(404).json({ error: { message: 'Document not found' } });
    const isOwner = String(doc.uploadedBy) === String(req.auth.userId);
    const isAdmin = req.auth.role === 'Admin';
    const verifierStatus = req.user?.verifierStatus || (req.user?.isVerifierApproved ? 'APPROVED' : 'PENDING');
    const isApprovedVerifier = req.auth.role === 'Verifier' && verifierStatus === 'APPROVED' && req.user?.organization === doc.issuingOrganization;
    if (!isOwner && !isAdmin && !isApprovedVerifier) return res.status(404).json({ error: { message: 'Document not found' } });

    let chain = null;
    try {
      chain = await getDocumentHashFromChain({ documentId });
    } catch (e) {
      chain = { sha256HashHex: '', timestamp: null };
    }

    const dbHash = normalizeSha256(doc.sha256Hash);
    const chainHash = normalizeSha256(chain.sha256HashHex);
    const hashMatches = compareHashesSecure(dbHash, chainHash);

    const status = doc.isRevoked || doc.status === 'revoked'
      ? 'REVOKED'
      : doc.status === 'rejected'
        ? 'REJECTED'
        : doc.expiryDate && new Date(doc.expiryDate).getTime() < Date.now()
          ? 'EXPIRED'
          : doc.status !== 'verified' || !doc.blockchain?.confirmed
            ? 'PENDING'
            : hashMatches
            ? 'VALID'
            : chainHash ? 'TAMPERED' : 'ERROR';

    const payload = buildVerificationCertificatePayload({
      document: doc,
      verification: {
        isAuthentic: status === 'VALID',
        verificationTimestamp: doc.blockchain?.timestamp ? new Date(doc.blockchain.timestamp * 1000).toISOString() : null,
        tamperDetectionResult: { hashMatches, details: hashMatches ? 'Uploaded hash matches on-chain record.' : 'Hash mismatch: possible tampering.' },
        hash: chainHash,
        blockchainHash: chainHash,
      },
      blockchain: {
        transactionId: doc.blockchain?.transactionId,
        confirmed: doc.blockchain?.confirmed,
        blockNumber: doc.blockchain?.blockNumber,
        timestamp: doc.blockchain?.timestamp,
        blockchainHash: chainHash,
      },
      status,
    });

    const frontendUrl = process.env.FRONTEND_BASE_URL || process.env.FRONTEND_URL || "";
    const verificationUrl = frontendUrl
      ? `${frontendUrl}/?verify=${encodeURIComponent(documentId)}`
      : `/?verify=${encodeURIComponent(documentId)}`;
    const qrCodeDataUrl = await generateQrCodeDataUrl(verificationUrl);

    if (format === 'pdf') {
      // Generate PDF
      const pdfBuffer = await generateCertificatePdf({ payload, qrDataUrl: qrCodeDataUrl });
      res.setHeader('Content-Type', 'application/pdf');
      res.setHeader('Content-Disposition', `attachment; filename="verification-certificate_${documentId}.pdf"`);
      return res.status(200).send(pdfBuffer);
    }

    // Default: HTML format
    const html = toHtmlTemplate({ payload });
    // Inject QR image
    const htmlWithQr = html.replace('id="qr">(QR QR-code rendered by server)</div>', `id="qr"><img src="${qrCodeDataUrl}" alt="Verification QR"/></div>`);

    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="verification-certificate_${documentId}.html"`);
    return res.status(200).send(htmlWithQr);
  } catch (err) {
    return next(err);
  }
}

module.exports = { generateCertificate };

